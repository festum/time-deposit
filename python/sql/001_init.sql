CREATE TABLE "timeDeposits" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "planType" TEXT NOT NULL,
    days INTEGER NOT NULL,
    balance NUMERIC(18, 5) NOT NULL
        CONSTRAINT time_deposits_balance_range
        CHECK (balance BETWEEN -1000000000000 AND 1000000000000)
);

CREATE TABLE withdrawals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timeDepositId" INTEGER NOT NULL REFERENCES "timeDeposits"(id),
    amount NUMERIC(18, 5) NOT NULL
        CONSTRAINT withdrawals_amount_range
        CHECK (amount BETWEEN -1000000000000 AND 1000000000000),
    date DATE NOT NULL
);

CREATE INDEX withdrawals_time_deposit_id_idx ON withdrawals ("timeDepositId");
